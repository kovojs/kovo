#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, '..');
const entryPath = resolve(repositoryRoot, 'packages/browser/src/deferred-app-runtime-entry.ts');
const outputPath = resolve(repositoryRoot, 'packages/browser/src/deferred-app-runtime-module.ts');
const identityOutputPath = resolve(
  repositoryRoot,
  'packages/browser/src/deferred-app-runtime-identity.ts',
);
const check = process.argv.includes('--check');

const result = await build({
  bundle: true,
  entryPoints: [entryPath],
  format: 'esm',
  legalComments: 'none',
  minify: true,
  platform: 'browser',
  target: ['es2022'],
  treeShaking: true,
  write: false,
});
const output = result.outputFiles?.[0]?.text;
if (typeof output !== 'string' || output.length === 0) {
  throw new Error('Browser deferred app runtime bundling produced no JavaScript.');
}
const modulePath = '/c/kovo-generated-app-runtime.client.js';
const digest = clientModuleRepresentationDigest(output);
const moduleHref = `/c/__v/${digest}/kovo-generated-app-runtime.client.js`;

const source = [
  '// Generated by scripts/generate-browser-deferred-app-runtime.mjs. Do not edit.',
  '/** @internal Exact compiler-owned browser representation. */',
  `export const kovoDeferredAppRuntimeModuleSource: string = ${JSON.stringify(output)};`,
  '',
].join('\n');
const identitySource = [
  '// Generated by scripts/generate-browser-deferred-app-runtime.mjs. Do not edit.',
  '/** @internal Canonical compiler-owned client-module path. */',
  `export const kovoDeferredAppRuntimeModulePath: string = '${modulePath}';`,
  '/** @internal Immutable href derived from the exact generated representation. */',
  'export const kovoDeferredAppRuntimeModuleHref: string =',
  `  '${moduleHref}';`,
  '',
].join('\n');

if (check) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  const currentIdentity = await readFile(identityOutputPath, 'utf8').catch(() => '');
  if (current !== source || currentIdentity !== identitySource) {
    throw new Error(
      'packages/browser/src/deferred-app-runtime-module.ts is stale; run pnpm --filter @kovojs/browser build:app-runtime.',
    );
  }
} else {
  await writeFile(outputPath, source, 'utf8');
  await writeFile(identityOutputPath, identitySource, 'utf8');
}

function clientModuleRepresentationDigest(source) {
  const hash = createHash('sha256');
  updateFrame(hash, 'domain', 'kovo-client-module-representation/v1');
  updateFrame(hash, 'content-type', 'text/javascript; charset=utf-8');
  updateFrame(hash, 'body', Buffer.from(source, 'utf8').toString('utf8'));
  return hash.digest('hex');
}

function updateFrame(hash, tag, value) {
  hash.update(`${Buffer.byteLength(tag, 'utf8')}:`);
  hash.update(tag);
  hash.update(`${Buffer.byteLength(value, 'utf8')}:`);
  hash.update(value);
}
