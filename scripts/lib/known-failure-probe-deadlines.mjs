import {
  DEV_READY_LISTENER_INFRASTRUCTURE_TIMEOUT_MS,
  DEV_READY_POST_BIND_BUDGET_MS,
} from './dev-ready-probe-contract.mjs';

/**
 * First-loop probes intentionally keep their behavioral phase deadlines independent. The register
 * process that encloses a whole probe must contain their serial worst case plus materialization,
 * result encoding, and bounded child cleanup. These constants keep the two layers from drifting.
 */
export const KNOWN_FAILURE_PACKED_SCAFFOLD_TIMEOUT_MS = 30_000;
export const KNOWN_FAILURE_PACKED_INSTALL_TIMEOUT_MS = 180_000;
export const KNOWN_FAILURE_PACKED_LIFECYCLE_TIMEOUT_MS = 120_000;
export const KNOWN_FAILURE_PACKED_REBUILD_TIMEOUT_MS = 120_000;
export const KNOWN_FAILURE_PACKED_BUILD_TIMEOUT_MS = 180_000;
export const KNOWN_FAILURE_PACKED_CHECK_TIMEOUT_MS = 240_000;
/** CI reachability ceiling only; this is not G1/G2 startup or first-response performance authority. */
export const KNOWN_FAILURE_FIRST_RESPONSE_INFRASTRUCTURE_TIMEOUT_MS = 120_000;
export const KNOWN_FAILURE_LOGIN_RESPONSE_TIMEOUT_MS = 30_000;
export const KNOWN_FAILURE_HTTP_ATTEMPT_TIMEOUT_MS = 2_000;
export const KNOWN_FAILURE_DEV_STOP_PHASE_TIMEOUT_MS = 3_000;
export const KNOWN_FAILURE_COMMAND_CLEANUP_PHASE_TIMEOUT_MS = 3_000;
export const KNOWN_FAILURE_RESPONSE_STABILITY_DELAY_MS = 100;
export const KNOWN_FAILURE_OUTER_PROCESS_HEADROOM_MS = 60_000;

const DEV_STOP_TIMEOUT_MS = 2 * KNOWN_FAILURE_DEV_STOP_PHASE_TIMEOUT_MS;
const COMMAND_CLEANUP_TIMEOUT_MS = 4 * KNOWN_FAILURE_COMMAND_CLEANUP_PHASE_TIMEOUT_MS;
const SERVED_INSTALL_TIMEOUT_MS =
  KNOWN_FAILURE_PACKED_INSTALL_TIMEOUT_MS +
  KNOWN_FAILURE_PACKED_LIFECYCLE_TIMEOUT_MS +
  KNOWN_FAILURE_PACKED_REBUILD_TIMEOUT_MS +
  3 * COMMAND_CLEANUP_TIMEOUT_MS;
const SERVED_APP_INNER_TIMEOUT_MS =
  KNOWN_FAILURE_PACKED_SCAFFOLD_TIMEOUT_MS +
  SERVED_INSTALL_TIMEOUT_MS +
  DEV_READY_LISTENER_INFRASTRUCTURE_TIMEOUT_MS +
  KNOWN_FAILURE_FIRST_RESPONSE_INFRASTRUCTURE_TIMEOUT_MS +
  KNOWN_FAILURE_LOGIN_RESPONSE_TIMEOUT_MS +
  KNOWN_FAILURE_RESPONSE_STABILITY_DELAY_MS +
  DEV_STOP_TIMEOUT_MS;

export const KNOWN_FAILURE_FIRST_LOOP_OUTER_TIMEOUT_FLOORS_MS = Object.freeze({
  'dev-ready':
    KNOWN_FAILURE_PACKED_SCAFFOLD_TIMEOUT_MS +
    SERVED_INSTALL_TIMEOUT_MS +
    DEV_READY_LISTENER_INFRASTRUCTURE_TIMEOUT_MS +
    DEV_READY_POST_BIND_BUDGET_MS +
    DEV_STOP_TIMEOUT_MS +
    KNOWN_FAILURE_OUTER_PROCESS_HEADROOM_MS,
  'opaque-boundary': SERVED_APP_INNER_TIMEOUT_MS + KNOWN_FAILURE_OUTER_PROCESS_HEADROOM_MS,
  'sqlite-login': SERVED_APP_INNER_TIMEOUT_MS + KNOWN_FAILURE_OUTER_PROCESS_HEADROOM_MS,
  'fresh-check':
    2 *
      (KNOWN_FAILURE_PACKED_SCAFFOLD_TIMEOUT_MS +
        KNOWN_FAILURE_PACKED_CHECK_TIMEOUT_MS +
        COMMAND_CLEANUP_TIMEOUT_MS) +
    KNOWN_FAILURE_OUTER_PROCESS_HEADROOM_MS,
  'transactional-build':
    KNOWN_FAILURE_PACKED_SCAFFOLD_TIMEOUT_MS +
    2 * (KNOWN_FAILURE_PACKED_BUILD_TIMEOUT_MS + COMMAND_CLEANUP_TIMEOUT_MS) +
    KNOWN_FAILURE_OUTER_PROCESS_HEADROOM_MS,
});
